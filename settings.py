"""
=====================================================================
 НАСТРОЙКИ ПРОЕКТА - единственный файл, который обычно нужно трогать
=====================================================================

Секреты (API_ID / API_HASH / BOT_TOKEN / ADMIN_IDS) НЕ храним прямо
тут - они берутся из переменных окружения (файл .env локально, или
вкладка "Environment" в Render). Так безопаснее: .env не попадает в
git, а секреты видно только там, где им положено быть.

Всё остальное, что можно захотеть поменять (задержка между сообщениями
рассылки, тексты кнопок, пути к данным и т.д.) - собрано здесь одним
списком, чтобы не лазить по коду бота.
=====================================================================
"""
import os
from dotenv import load_dotenv

load_dotenv()

# ---------------------------------------------------------------------------
# 1. СЕКРЕТЫ (заполняются в .env локально / в Render -> Environment)
# ---------------------------------------------------------------------------

# my.telegram.org -> API development tools
API_ID = int(os.getenv("API_ID", "0"))
API_HASH = os.getenv("API_HASH", "")

# Токен бота-панели, выданный @BotFather
BOT_TOKEN = os.getenv("BOT_TOKEN", "")

# Кто может пользоваться панелью управления (свои Telegram user id через запятую)
ADMIN_IDS = {int(x) for x in os.getenv("ADMIN_IDS", "").split(",") if x.strip()}

# ---------------------------------------------------------------------------
# 2. ГДЕ ХРАНИТЬ ДАННЫЕ
# ---------------------------------------------------------------------------
#
# ВАЖНО про Render: диск сервиса эфемерный - при каждом передеплое файлы
# стираются. Чтобы сессии Telethon (вход в аккаунты) и база рассылки не
# терялись, в render.yaml к сервису подключен Persistent Disk, примонтированный
# именно в STORAGE_DIR. Если меняете значение ниже - поменяйте и mountPath
# в render.yaml (см. файл render.yaml).
STORAGE_DIR = os.getenv("STORAGE_DIR", "storage")

SESSIONS_DIR = f"{STORAGE_DIR}/sessions"
DATA_DIR = f"{STORAGE_DIR}/data"

MONITOR_SESSION = f"{SESSIONS_DIR}/monitor_account"      # сессия аккаунта-сборщика
BROADCAST_SESSION = f"{SESSIONS_DIR}/broadcast_account"  # сессия аккаунта-рассыльщика

GROUPS_FILE = f"{DATA_DIR}/groups.json"                  # какие группы мониторим
SUBSCRIBERS_FILE = f"{DATA_DIR}/subscribers.json"        # база рассылки (авто + вручную)
BROADCAST_MESSAGE_FILE = f"{DATA_DIR}/broadcast_message.json"  # текст рассылки

os.makedirs(SESSIONS_DIR, exist_ok=True)
os.makedirs(DATA_DIR, exist_ok=True)

# ---------------------------------------------------------------------------
# 3. МОНИТОРИНГ (работает 24/7)
# ---------------------------------------------------------------------------

# Мониторинг запускается автоматически при старте процесса и работает
# постоянно в фоне. Если аккаунт мониторинга ещё не авторизован, или
# соединение оборвалось - через сколько секунд повторить попытку.
MONITOR_RETRY_SECONDS = float(os.getenv("MONITOR_RETRY_SECONDS", "30"))

# ---------------------------------------------------------------------------
# 4. ПОВЕДЕНИЕ РАССЫЛКИ
# ---------------------------------------------------------------------------

# Пауза между отправками сообщений при рассылке с личного аккаунта (сек).
# Чем меньше значение - тем выше риск получить ограничения от Telegram
# на "аккаунте для рассылки". Не ставьте меньше 1-2 секунд.
BROADCAST_DELAY_SECONDS = float(os.getenv("BROADCAST_DELAY_SECONDS", "2.5"))

# Текст кнопки под сообщением в режиме "рассылка от бота"
ACK_BUTTON_TEXT = "👍 Принято"

# Максимальная длина кода подтверждения, который набирают кнопками
MAX_CODE_LENGTH = 10

# ---------------------------------------------------------------------------
# 5. АВТО-СНЯТИЕ СПАМ-БЛОКА ПРИ РАССЫЛКЕ
# ---------------------------------------------------------------------------
#
# Если сообщение не удалось отправить, аккаунт рассылки сам пишет /start
# официальному боту @SpamBot, чтобы попытаться снять ограничение (на
# аккаунтах с Telegram Premium это часто снимает блок сразу), ждёт
# SPAMBLOCK_RETRY_DELAY_SECONDS и повторяет отправку один раз. Если и это
# не помогло - получатель попадает в список ошибок в отчёте, но рассылка
# идёт дальше и не останавливается на нём.
ENABLE_SPAMBOT_RECOVERY = os.getenv("ENABLE_SPAMBOT_RECOVERY", "true").lower() == "true"
SPAMBOT_USERNAME = os.getenv("SPAMBOT_USERNAME", "SpamBot")
SPAMBLOCK_RETRY_DELAY_SECONDS = float(os.getenv("SPAMBLOCK_RETRY_DELAY_SECONDS", "3"))

# ---------------------------------------------------------------------------
# 6. HEALTH-CHECK / KEEP-ALIVE (чтобы Render не усыплял сервис)
# ---------------------------------------------------------------------------
#
# Бот поднимает лёгкий HTTP-сервер, отвечающий "ok" на GET /health.
# Render Cron Job (см. render.yaml) дёргает этот адрес каждые 10 минут,
# чтобы сервис не засыпал. Порт задаёт сам Render через переменную PORT -
# трогать не нужно, но если хотите поменять локально - можно через .env.
HEALTHCHECK_PORT = int(os.getenv("PORT", "8080"))
